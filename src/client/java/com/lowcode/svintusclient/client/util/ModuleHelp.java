    private static void register(String name, String what, String look, String cond) {
        HELP_MAP.put(name.toLowerCase(), new HelpInfo(name, what, look, cond));
    }

    public static HelpInfo get(Module module) {
        if (module == null) return null;
        return get(module.getName());
    }

    public static HelpInfo get(String name) {
        if (name == null) return null;
        HelpInfo info = HELP_MAP.get(name.toLowerCase());
        if (info != null) return info;
        for (Map.Entry<String, HelpInfo> entry : HELP_MAP.entrySet()) {
            if (name.toLowerCase().contains(entry.getKey()) || entry.getKey().contains(name.toLowerCase())) {
                return entry.getValue();
            }
        }
        return new HelpInfo(name, "Визуальный модуль улучшения интерфейса и эффектов.", "Качественный рендеринг в едином стиле SvintusClient.", "Безопасен для серверов.");
    }
